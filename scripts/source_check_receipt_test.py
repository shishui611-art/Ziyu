#!/usr/bin/env python3
"""Exercise successful reuse and rejection with real isolated Git/source trees."""
import contextlib
import io
import json
import os
from pathlib import Path
import shutil
import subprocess
import tempfile
import unittest

import source_check_receipt as gate


class SourceReceiptTest(unittest.TestCase):
    def setUp(self):
        temporary = tempfile.TemporaryDirectory()
        self.addCleanup(temporary.cleanup)
        self.root = Path(temporary.name)
        (self.root / "scripts").mkdir()
        (self.root / "common/python").mkdir(parents=True)
        self.check = self.root / "scripts/check.sh"
        self.check.write_bytes(b"#!/bin/sh\nprintf 'ran\\n' >> check-count\n")
        self.source = self.root / "source.txt"
        self.source.write_bytes(b"source\n")
        (self.root / "scripts/module_payload_manifest.txt").write_bytes(b"source.txt\ncommon/python\n")
        self.runtime = self.root / "common/python/runtime.py"
        self.runtime.write_bytes(b"runtime\n")
        self.git("init", "-q")
        self.git("add", "scripts", "source.txt")
        self.git("commit", "-qm", "fixture")
        self.receipt = self.root / "receipt.json"

    def git(self, *args):
        return subprocess.run(
            ["git", "-C", str(self.root), "-c", "user.name=Fixture", "-c",
             "user.email=fixture@example.invalid", *args], check=True, capture_output=True)

    def run_and_verify(self):
        self.assertEqual(gate.run_checks(self.root, self.receipt), 0)
        gate.verify_receipt(self.root, self.receipt)

    def test_success_reuses_check_without_executing_it_again(self):
        self.run_and_verify()
        gate.verify_receipt(self.root, self.receipt)
        self.assertEqual((self.root / "check-count").read_bytes(), b"ran\n")

    def test_changed_tracked_source_rejects_receipt(self):
        self.run_and_verify()
        self.source.write_bytes(b"changed\n")
        with self.assertRaises(gate.ReceiptError):
            gate.verify_receipt(self.root, self.receipt)

    def test_changed_downloaded_runtime_rejects_receipt(self):
        self.run_and_verify()
        self.runtime.write_bytes(b"changed runtime\n")
        with self.assertRaises(gate.ReceiptError):
            gate.verify_receipt(self.root, self.receipt)

    def test_added_payload_file_rejects_receipt(self):
        self.run_and_verify()
        (self.runtime.parent / "added.py").write_bytes(b"new runtime input\n")
        with self.assertRaises(gate.ReceiptError):
            gate.verify_receipt(self.root, self.receipt)

    def test_generated_bytecode_and_unrelated_private_files_are_not_inputs(self):
        self.run_and_verify()
        cache = self.runtime.parent / "__pycache__"
        cache.mkdir()
        (cache / "runtime.pyc").write_bytes(b"generated bytecode")
        (self.root / "private-user-font.ttf").write_bytes(b"not part of the build")
        gate.verify_receipt(self.root, self.receipt)

    def test_new_commit_with_same_source_still_requires_new_checks(self):
        self.run_and_verify()
        self.git("commit", "--allow-empty", "-qm", "different commit")
        with self.assertRaises(gate.ReceiptError):
            gate.verify_receipt(self.root, self.receipt)

    def test_receipt_transfers_to_identical_checkout_and_runtime(self):
        self.run_and_verify()
        temporary = tempfile.TemporaryDirectory()
        self.addCleanup(temporary.cleanup)
        other = Path(temporary.name) / "checkout"
        shutil.copytree(self.root, other, symlinks=True)
        gate.verify_receipt(other, other / "receipt.json")

    def test_source_changed_during_checks_does_not_get_receipt(self):
        self.check.write_bytes(b"#!/bin/sh\nprintf 'changed\\n' >> source.txt\n")
        with self.assertRaises(gate.ReceiptError):
            gate.run_checks(self.root, self.receipt)
        self.assertFalse(self.receipt.exists())

    def test_failed_check_invalidates_previous_success_receipt(self):
        self.run_and_verify()
        self.check.write_bytes(b"#!/bin/sh\nexit 7\n")
        self.assertEqual(gate.run_checks(self.root, self.receipt), 7)
        self.assertFalse(self.receipt.exists())

    def test_missing_or_failed_receipt_cannot_skip_checks(self):
        with self.assertRaises(FileNotFoundError):
            gate.verify_receipt(self.root, self.receipt)
        self.receipt.write_text(json.dumps({"schema": gate.SCHEMA, "state": "failed"}), encoding="utf-8")
        with self.assertRaises(gate.ReceiptError):
            gate.verify_receipt(self.root, self.receipt)


if __name__ == "__main__":
    # Keep source CI logs compact; real check process failures remain on stderr.
    with contextlib.redirect_stdout(io.StringIO()):
        unittest.main(verbosity=2)
